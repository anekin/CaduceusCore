# =============================================================================
# Remote stage runner (setsid + detached watchdog, no stray simv on SSH drop)
# =============================================================================
run_remote_stage() {
  local name="$1" timeout_s="$2" logfile="$3" body="$4"
  local stage_rc ssh_rc
  log "Stage ${name}: start ($(date -u +%Y-%m-%dT%H:%M:%SZ), timeout=${timeout_s}s)" >&2
  body=${body//__ROOT__/$ROOT}
  local remote_cmd
  remote_cmd="set +e
TMPSTAGE=/tmp/p10f3_${name}_\$\$.sh
cat > \"\$TMPSTAGE\" <<'STAGE_EOF'
${body}
STAGE_EOF
setsid bash \"\$TMPSTAGE\" &
SPID=\$!
setsid bash -c 'sleep ${timeout_s}; kill -TERM -\$1 2>/dev/null; sleep 10; kill -KILL -\$1 2>/dev/null' _ \$SPID </dev/null >/dev/null 2>&1 &
KILLER=\$!
wait \$SPID
rc=\$?
kill -TERM -\$KILLER 2>/dev/null
sleep 1
kill -KILL -\$KILLER 2>/dev/null
echo \"STAGE_EXIT=\$rc\"
rm -f \"\$TMPSTAGE\"
exit 0"
  p10_ssh "$remote_cmd" > "$logfile" 2>&1
  ssh_rc=$?
  stage_rc=$(grep -oE '^STAGE_EXIT=[0-9]+' "$logfile" | tail -1 | cut -d= -f2)
  [ -n "$stage_rc" ] || stage_rc="ssh-error-${ssh_rc}"
  log "Stage ${name}: done (STAGE_EXIT=${stage_rc})" >&2
  echo "$stage_rc"
}

