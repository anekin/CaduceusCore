#                                    which is regenerated by every F3 run) are
#                                    hashed and verified against the recorded
#                                    manifest build/evidence/
#                                    ph10-task-evidence-manifest.sha256.
#                                    First run bootstraps the manifest.
#
# Evidence integrity: the PERF batches write their JSONL results into
# build/evidence/{w4-perf-p*,fullchain-pipeline}.txt by design.  F3 saves the
# committed copies first, parses the fresh reproduction results, then restores
# the committed copies and verifies the restore is bit-exact — so NO evidence
# file is modified by the end of a run.  The task-* evidence files are checked
# before and after the reproductions; any modification (other than task-13,
# which the mandated re-run of scripts/p10_36layer_ibex.sh regenerates) fails
# the run.
#
# Exit codes:
#   0  all three key evidences reproducible + manifest match/bootstrap
#   1  any reproduction FAIL or manifest mismatch/tamper
#
# Usage (from repo root, on sz0002; drives sz0001 via p10_ssh):
#   bash scripts/p10_f3_manual_qa.sh
# =============================================================================
