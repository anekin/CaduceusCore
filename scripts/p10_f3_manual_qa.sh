make_batch_body() {
  cat <<'STAGE_EOF'
set -euo pipefail
export PYTHONPATH="${PYTHONPATH:-}:__ROOT__"
export MODULE=sim.perf_tests
export TOPLEVEL=tb_soc_ibex
export TOPLEVEL_LANG=verilog
export FM_SOC_RTL_MODE=ibex
export BOOTROM_HEX="__ROOT__/firmware/build/npu_firmware.hex"
export TESTCASE=__TESTCASE__
cd "$(cd __ROOT__/.. && pwd)"
echo "[p10_f3] Running __TESTCASE__ ..."
"__ROOT__/build/ibex_full_rtl/simv_soc_ibex" +COCOTB +BOOTROM_HEX="$BOOTROM_HEX"
echo "[p10_f3] __TESTCASE__ done."
STAGE_EOF
}

STAGE_RCS=""
for BATCH_ENTRY in "${BATCHES[@]}"; do
  IFS='|' read -r TESTCASE EVFILE DESC <<< "${BATCH_ENTRY}"
  echo ""
  echo "── ${TESTCASE} — ${DESC} ──"
  BODY="$(make_batch_body)"
  BODY=${BODY//__TESTCASE__/$TESTCASE}
  STAGELOG="$F3_TMP/stage-${TESTCASE}.log"
  RC=$(run_remote_stage "${TESTCASE}" "$STAGE_TIMEOUT" "$STAGELOG" "$BODY")
  STAGE_RCS="${STAGE_RCS} ${TESTCASE}=${RC}"
  if [ "$RC" != "0" ]; then
    fail "stage ${TESTCASE} exited ${RC}; see log tail:"
    tail -15 "$STAGELOG" || true
  fi
  sleep 3  # let NFS flush the JSONL evidence files before parsing
done

# Parse the fresh reproduction results (all 21 cases PASS, cos_sim >= 0.999).
PERF_PARSE_OK=1
P10F3_EVID="$EVID" P10F3_RESULTS="$F3_TMP/results.tsv" python3 <<'PYEOF'
import json
import os
import sys

EVID = os.environ["P10F3_EVID"]
OUT = os.environ["P10F3_RESULTS"]

expected = {
    "w4-perf-p0.txt": ["PERF-01", "PERF-02", "PERF-03", "PERF-04"],
    "w4-perf-p1.txt": ["PERF-05", "PERF-06", "PERF-07", "PERF-08"],
    "w4-perf-p2.txt": ["PERF-09", "PERF-10", "PERF-11", "PERF-12"],
    "w4-perf-p3.txt": ["PERF-13", "PERF-14", "PERF-15", "PERF-16"],
    "w4-perf-p4.txt": ["PERF-17", "PERF-18", "PERF-19", "PERF-20"],
    "fullchain-pipeline.txt": ["FULLCHAIN"],
}

rows = []
problems = []
for fname, cids in expected.items():
    path = os.path.join(EVID, fname)
    by_id = {}
    if os.path.isfile(path):
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            try:
                d = json.loads(line)
            except Exception:
                continue
            cid = d.get("case_id")
            if cid:
                by_id[cid] = d
    for cid in cids:
        d = by_id.get(cid)
        if d is None:
            rows.append((cid, "MISSING", "-", "-", fname))
            problems.append(f"{cid}: missing in {fname}")
            continue
        st = str(d.get("status", "?"))
        cs = d.get("cos_sim")
        cs_s = ("%.6f" % float(cs)) if isinstance(cs, (int, float)) else "-"
        cyc = str(d.get("cycles", "-"))
        rows.append((cid, st, cs_s, cyc, fname))
        if st != "PASS":
            problems.append(f"{cid}: status={st} in {fname}")
        elif cs_s != "-" and float(cs) < 0.999:
            problems.append(f"{cid}: cos_sim={cs_s} < 0.999 in {fname}")

with open(OUT, "w", encoding="utf-8") as f:
    for r in rows:
        f.write("\t".join(r) + "\n")

print(f"[p10_f3] parsed {len(rows)} fresh PERF cases")
if problems:
    print("PROBLEMS:")
    for p in problems:
        print("  " + p)
    sys.exit(1)
print("[p10_f3] all fresh PERF cases PASS (cos_sim >= 0.999 where applicable)")
PYEOF
PERF_PARSE_OK=$?
TOTAL=$(wc -l < "$F3_TMP/results.tsv" | tr -d ' ')
PERF06_CS=$(awk -F'\t' '$1=="PERF-06" {print $3}' "$F3_TMP/results.tsv")
PERF06_ST=$(awk -F'\t' '$1=="PERF-06" {print $2}' "$F3_TMP/results.tsv")
P0_SAMPLE_CS=$(awk -F'\t' '$1=="PERF-01" || $1=="PERF-02" || $1=="PERF-03" || $1=="PERF-04" {print $3}' "$F3_TMP/results.tsv" | tr '\n' ' ')

if [ "$PERF_PARSE_OK" -ne 0 ] || [ "$TOTAL" != "21" ] \
   || [ "$PERF06_ST" != "PASS" ] || ! python3 -c "import sys; sys.exit(0 if float('${PERF06_CS:-0}') >= 0.999 else 1)"; then
  fail "PERF reproduction NOT green: parsed=${TOTAL}/21 PERF-06 status=${PERF06_ST:-?} cos_sim=${PERF06_CS:-parse-error}"
else
  log "  PERF reproduction: ${TOTAL}/21 PASS, PERF-06 cos_sim=${PERF06_CS}"
fi

# todo-5 PERF p0 sample (batch 1) verdict.
if [ "$PERF_PARSE_OK" -eq 0 ]; then
  DMA_PERF_SAMPLE_OK="PASS"
  log "  todo-5 PERF p0 sample: PASS (PERF-01..04 all PASS)"
else
  DMA_PERF_SAMPLE_OK="FAIL"
fi

# testcase-list sync state (static, committed by todo 9).
if grep -q 'Phase 10 状态: PASS 21 | NOT RESOLVED 0' "$TC_LIST" \
   && grep -qE '^\| PERF-06 \|.*\| ✅ PASS \|' "$TC_LIST"; then
  TC_SYNC_OK=1
  log "  testcase-list: 21/21 PASS, stats line synced (rtl/testcase-list-perf.md)"
else
  fail "testcase-list not synced (PERF-06 row or stats line missing)"
  TC_SYNC_OK=0
fi

# Restore the committed PERF evidence copies and verify bit-exact restore.
for f in "${PERF_FILES[@]}"; do
  if [ -f "$F3_TMP/saved/$f" ]; then cp -p "$F3_TMP/saved/$f" "$EVID/$f"; else rm -f "$EVID/$f"; fi
done
sleep 1
if (cd "$EVID" && sha256sum -c "$F3_TMP/saved.sha256" > "$F3_TMP/restore.log" 2>&1); then
  log "  PERF evidence restored bit-exact (committed copies intact)"
else
  fail "PERF evidence restore NOT bit-exact!"
  cat "$F3_TMP/restore.log" | grep -E 'FAILED' || true
fi

# =============================================================================
# Phase 4 — Ibex 36-layer checkpoint-subset segment run (todo 13)
# =============================================================================
log "=== Phase 4: Ibex segment run (todo 13, 9-layer checkpoint subset) ==="
IBEX_OK=1
IBEX_RC="skipped"
IBEX_LOG="$EVID/task-F3-ibex.log"
# Concurrency guard: run_ibex_segment_run.sh exits via `pkill -f
# simv_soc_ibex_seg`, which would kill an unrelated concurrent segment run.
if p10_ssh "pgrep -f simv_soc_ibex_seg" >/dev/null 2>&1; then
  fail "another simv_soc_ibex_seg is running on sz0001 — refusing to overlap (re-run F3 after it finishes)"
  IBEX_OK=0
else
  log "  running bash scripts/p10_36layer_ibex.sh (timeout=${IBEX_TIMEOUT}s)..."
  timeout "$IBEX_TIMEOUT" bash "$IBEX_SCRIPT" > "$IBEX_LOG" 2>&1
  IBEX_RC=$?
  if [ "$IBEX_RC" -ne 0 ]; then
    fail "p10_36layer_ibex.sh exited ${IBEX_RC} (log: ${IBEX_LOG})"
    tail -30 "$IBEX_LOG" || true
    IBEX_OK=0
  elif grep -q 'ALL ASSERTIONS PASS' "$IBEX_LOG"; then
    log "  p10_36layer_ibex.sh: ALL ASSERTIONS PASS"
  else
    fail "p10_36layer_ibex.sh rc=0 but assertions not confirmed in log"
    IBEX_OK=0
  fi
fi

# Independent re-verification of the todo-13 evidence fields (only when the
# segment run was actually attempted; the concurrency guard already records
# its own FAIL otherwise).
T13_EVID="$EVID/task-13-phase10-rtl-verification.txt"
if [ "$IBEX_RC" = "skipped" ]; then
  :  # guard already recorded the FAIL
elif [ ! -f "$T13_EVID" ]; then
  fail "task-13 evidence missing after segment run: $T13_EVID"
  IBEX_OK=0
else
  for field in "engine=ibex" "ibex_executed=L0,L9,L10,L19,L20,L29,L30,L34,L35" \
               "checkpoints=L0,L10,L20,L30,L35" "chain_restart=true" \
               "chain_restart_state_source=ibex_dram" "segment_input_source=spike_npz" \
               "LADDER=PASS"; do
    grep -qF "$field" "$T13_EVID" \
      && log "  evidence field OK   : $field" \
      || { fail "evidence field missing: $field"; IBEX_OK=0; }
  done
fi

# =============================================================================
# Phase 5 — Manifest post-check + record + final evidence
# =============================================================================
log "=== Phase 5: manifest post-check ==="
(cd "$EVID" && ls task-*-phase10-rtl-verification.txt 2>/dev/null \
    | grep -v '^task-F3-' | xargs -r sha256sum) > "$F3_TMP/post.sha256" 2>/dev/null || true

MANIFEST_CLASSIFY="$(P10F3_PRE="$F3_TMP/pre.sha256" P10F3_POST="$F3_TMP/post.sha256" python3 <<'PYEOF'
import os
import sys

def load(p):
    d = {}
    if os.path.isfile(p):
        for line in open(p, encoding="utf-8"):
            line = line.strip()
            if line:
                parts = line.split(None, 1)
                if len(parts) == 2:
                    d[parts[1]] = parts[0]
    return d

pre = load(os.environ["P10F3_PRE"])
post = load(os.environ["P10F3_POST"])
added = sorted(set(post) - set(pre))
removed = sorted(set(pre) - set(post))
changed = sorted(f for f in set(pre) & set(post) if pre[f] != post[f])
print(f"added={','.join(added) or '-'}")
print(f"removed={','.join(removed) or '-'}")
print(f"changed={','.join(changed) or '-'}")
PYEOF
)"
MANIFEST_ADDED=$(echo "$MANIFEST_CLASSIFY" | grep '^added=' | cut -d= -f2-)
MANIFEST_REMOVED=$(echo "$MANIFEST_CLASSIFY" | grep '^removed=' | cut -d= -f2-)
MANIFEST_CHANGED=$(echo "$MANIFEST_CLASSIFY" | grep '^changed=' | cut -d= -f2-)
log "  manifest diff: added=[${MANIFEST_ADDED}] removed=[${MANIFEST_REMOVED}] changed=[${MANIFEST_CHANGED}]"

MANIFEST_TAMPER=0
# Removed files are always a failure (evidence deleted during reproduction).
[ "$MANIFEST_REMOVED" = "-" ] || { fail "task evidence removed during run: ${MANIFEST_REMOVED}"; MANIFEST_TAMPER=1; }
# Changed files: only task-13 is tolerated, and only when the Ibex phase
# (which regenerates it) passed.
if [ "$MANIFEST_CHANGED" != "-" ]; then
  for f in ${MANIFEST_CHANGED//,/ }; do
    if [ "$f" = "task-13-phase10-rtl-verification.txt" ] && [ "$IBEX_OK" = "1" ]; then
      log "  task-13 evidence regenerated by the F3 Ibex reproduction (expected)"
    else
      fail "task evidence modified during run: $f"
      MANIFEST_TAMPER=1
    fi
  done
fi
# Unexpected additions (other than task-13 created by the Ibex reproduction).
if [ "$MANIFEST_ADDED" != "-" ]; then
  for f in ${MANIFEST_ADDED//,/ }; do
    if [ "$f" = "task-13-phase10-rtl-verification.txt" ] && [ "$IBEX_OK" = "1" ]; then
      log "  task-13 evidence created by the F3 Ibex reproduction (expected)"
    else
      log "  NOTE: new task evidence appeared: $f (recorded in manifest)"
    fi
  done
fi

# Write/refresh the canonical manifest.
(cd "$EVID" && ls task-*-phase10-rtl-verification.txt 2>/dev/null \
    | grep -v '^task-F3-' | xargs -r sha256sum) > "$MANIFEST"
MANIFEST_COUNT=$(wc -l < "$MANIFEST" | tr -d ' ')

if [ "$MANIFEST_PRE" = "NONE" ]; then
  MANIFEST_STATUS="RECORDED (bootstrap: first F3 run)"
  log "  manifest recorded (bootstrap): ${MANIFEST_COUNT} files"
elif [ "$MANIFEST_PRE" = "MISMATCH" ] || [ "$MANIFEST_TAMPER" = "1" ]; then
  MANIFEST_STATUS="MISMATCH"
else
  if [ "$MANIFEST_CHANGED" = "-" ] && [ "$MANIFEST_ADDED" = "-" ] && [ "$MANIFEST_REMOVED" = "-" ]; then
    MANIFEST_STATUS="MATCH (no evidence changed)"
    log "  manifest matches recorded state: ${MANIFEST_COUNT} files"
  else
    MANIFEST_STATUS="UPDATED (task-13 regenerated by F3 reproduction)"
    log "  manifest re-recorded: ${MANIFEST_COUNT} files"
  fi
fi

# =============================================================================
# Verdict
# =============================================================================
TS_END="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
DMA_OK=1
[ "$DMA_STATIC_OK" = "1" ] && [ "$DMA_E2E_OK" = "1" ] && [ "$DMA_PERF_SAMPLE_OK" = "PASS" ] || DMA_OK=0
PERF06_OK=1
[ "$PERF_PARSE_OK" = "0" ] && [ "$TOTAL" = "21" ] && [ "$PERF06_ST" = "PASS" ] && [ "$TC_SYNC_OK" = "1" ] || PERF06_OK=0
MANIFEST_OK=1
[ "$MANIFEST_STATUS" = "MISMATCH" ] && MANIFEST_OK=0
[ "$MANIFEST_PRE" = "MISMATCH" ] && MANIFEST_OK=0
[ "$MANIFEST_TAMPER" = "1" ] && MANIFEST_OK=0

VERDICT="PASS"
if [ "$F3_FAIL" -ne 0 ] || [ "$DMA_OK" -ne 1 ] || [ "$PERF06_OK" -ne 1 ] \
   || [ "$IBEX_OK" -ne 1 ] || [ "$MANIFEST_OK" -ne 1 ]; then
  VERDICT="FAIL"
fi

{
