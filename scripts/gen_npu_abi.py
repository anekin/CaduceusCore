# Firmware header generator
# ═════════════════════════════════════════════════════════════════════

def gen_firmware_header(schema: dict[str, Any]) -> str:
    """Generate bare-metal firmware header (compatible with npu-regmap.h pattern)."""
    lines: list[str] = []
    lines.append(f"/* {GENERATED_MARKER} */")
    lines.append(f"/* ABI version: {schema['abi']['version_string']} */")
    lines.append(f"/* Include this alongside npu-regmap.h; it provides verifiable constants */")
    lines.append(f"/* for static_assert validation of ABI compliance. */")
    lines.append("")
    lines.append(f"#ifndef NPU_ABI_FIRMWARE_H")
    lines.append(f"#define NPU_ABI_FIRMWARE_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")

    # ABI version
    lines.append(f"#define NPU_ABI_MAJOR {schema['abi']['major']}")
    lines.append(f"#define NPU_ABI_MINOR {schema['abi']['minor']}")
    lines.append("")

    # Base address checks
    lines.append("/* ── ABI Base Address Constants (for static_assert) ──────────── */")
    for name in sorted(schema["address_regions"]):
        reg = schema["address_regions"][name]
        base = int(reg["base"], 16)
        size = int(reg["size"], 16)
        lines.append(f"#define NPU_ABI_{name}_BASE 0x{base:08X}UL")
        lines.append(f"#define NPU_ABI_{name}_SIZE 0x{size:08X}UL")
    lines.append("")

    # Descriptor sizes for static_assert
    lines.append("/* ── ABI Descriptor Sizes (for static_assert) ────────────────── */")
    for desc_name in sorted(schema["descriptors"]):
        if desc_name == "description":
            continue
        desc = schema["descriptors"][desc_name]
        lines.append(f"#define NPU_ABI_DESC_{desc_name}_PACKED_SIZE {desc['packed_size']}")
        lines.append(f"#define NPU_ABI_DESC_{desc_name}_FIELD_COUNT {desc['field_count']}")
    lines.append("")

    # Each descriptor field offset for static_assert
    for desc_name in sorted(schema["descriptors"]):
        if desc_name == "description":
            continue
        desc = schema["descriptors"][desc_name]
        lines.append(f"/* ── ABI {desc_name} Descriptor Field Offsets ────────────────── */")
        for field in desc["fields"]:
            lines.append(f"#define NPU_ABI_DESC_{desc_name}_{field['name']}_OFFSET {field['offset']}")
        lines.append("")

    # Ring sizes
    lines.append("/* ── ABI Ring Buffer Configuration ──────────────────────────── */")
    rc = schema["rings"]["configuration"]
    lines.append(f"#define NPU_ABI_RING_ENTRIES {rc['ring_entries']}")
    lines.append(f"#define NPU_ABI_CMD_ENTRY_SIZE {rc['cmd_entry_size']}")
    lines.append(f"#define NPU_ABI_COMPLETION_ENTRY_SIZE {rc['completion_entry_size']}")
    lines.append("")

    # Engine opcodes
    lines.append("/* ── ABI Engine Opcodes ─────────────────────────────────────── */")
    opcode_values = schema["opcodes"]["values"]
    for name in sorted(opcode_values, key=lambda n: opcode_values[n]["value"]):
        oc = opcode_values[name]
        lines.append(f"#define NPU_ABI_ENGINE_OP_{name} {oc['value']}  /* {oc['engine']} */")
    lines.append("")

    # Status codes
    lines.append("/* ── ABI Status Codes ───────────────────────────────────────── */")
    for name in sorted(schema["status_codes"]["values"],
                        key=lambda n: schema["status_codes"]["values"][n]["value"]):
        sc = schema["status_codes"]["values"][name]
        lines.append(f"#define NPU_ABI_STATUS_{name} {sc['value']}")
    lines.append("")

    # DOORBELL known discrepancy note
    lines.append("/* ── Known Discrepancy: DOORBELL COMPLETION_STATUS ──────────── */")
    lines.append("/* COMPLETION_STATUS hardware window is 16 entries (offset 0x14). */")
    lines.append("/* Firmware writes COMPLETION_STATUS[cmd_id] with cmd_id up to */")
    lines.append(f"/* NPU_ABI_RING_ENTRIES-1 ({rc['ring_entries'] - 1}). This is a */")
    lines.append("/* known design gap that must be resolved in a future ABI revision. */")
    lines.append("")

    lines.append("#endif /* NPU_ABI_FIRMWARE_H */")
    lines.append("")

    return "\n".join(lines)


