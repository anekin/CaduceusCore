def main() -> None:
    parser = argparse.ArgumentParser(
        description="NPU ABI Schema Generator — deterministic bindings from spec/npu_abi.json"
    )
    parser.add_argument(
        "--generate", action="store_true",
        help="Generate all artifacts into gen/ directory"
    )
    parser.add_argument(
        "--check", action="store_true",
        help="Verify generated artifacts match schema (exit 0 on match, 1 on mismatch)"
    )
    args = parser.parse_args()

    if not args.generate and not args.check:
        parser.print_help()
        sys.exit(2)

    schema = load_schema()

    if args.check:
        print(f"Checking ABI v{schema['abi']['version_string']} generated artifacts...")
        ok = check_artifacts(schema)
        if ok:
            print(f"✅ All generated artifacts match the schema.")
            sys.exit(0)
        else:
            print(f"❌ Generated artifacts are out of date. Run --generate to update.")
            sys.exit(1)

    if args.generate:
        out_dir = REPO / "gen"
        print(f"Generating ABI v{schema['abi']['version_string']} artifacts into {out_dir}/ ...")
        written = generate_all(schema, out_dir)
        for p in written:
            print(f"  {p.name}")
        print(f"✅ {len(written)} artifacts generated.")


if __name__ == "__main__":
    main()
