GENERATORS = {
    "gen/npu_abi.py":             gen_python,
    "gen/npu_abi.h":              gen_c_header,
    "gen/npu_abi_firmware.h":     gen_firmware_header,
    "gen/npu_abi_pkg.sv":         gen_sv_package,
    "gen/npu_abi.md":             gen_markdown,
}


def generate_all(schema: dict[str, Any], out_dir: Path) -> list[Path]:
    """Generate all artifacts into out_dir. Returns list of paths written."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for rel_path, gen_fn in sorted(GENERATORS.items()):
        content = gen_fn(schema)
        target = out_dir / Path(rel_path).name
        target.write_text(content, encoding="utf-8")
        written.append(target)
    return written


def check_artifacts(schema: dict[str, Any]) -> bool:
    """Generate into temp dir, compare with existing files. Returns True if all match."""
    repo_gen = REPO / "gen"
    with tempfile.TemporaryDirectory(prefix="npu_abi_check_") as tmp:
        tmp_dir = Path(tmp)
        generate_all(schema, tmp_dir)
        all_ok = True
        for rel_path in sorted(GENERATORS):
            target_name = Path(rel_path).name
            existing = repo_gen / target_name
            generated = tmp_dir / target_name
            if not existing.is_file():
                print(f"  MISSING: {target_name}")
                all_ok = False
                continue
            if not filecmp.cmp(str(existing), str(generated), shallow=False):
                print(f"  MISMATCH: {target_name}")
                all_ok = False
            else:
                print(f"  OK: {target_name}")
    return all_ok


