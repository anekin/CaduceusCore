# Markdown documentation generator
# ═════════════════════════════════════════════════════════════════════

def gen_markdown(schema: dict[str, Any]) -> str:
    """Generate human-readable Markdown reference."""
    lines: list[str] = []
    lines.append(f"<!-- {GENERATED_MARKER} -->")
    lines.append("")
    lines.append(f"# CaduceusCore NPU ABI v{schema['abi']['version_string']}")
    lines.append("")
    lines.append(f"> **Endianness:** {schema['abi']['endianness']}-endian | "
                 f"**Register width:** {schema['abi']['register_width']}-bit | "
                 f"**Address granularity:** {schema['abi']['address_granularity']} bytes")
    lines.append("")
    lines.append("## Address Map")
    lines.append("")
    lines.append("| Region | Base | Size | Description |")
    lines.append("|--------|------|------|-------------|")
    for name in sorted(schema["address_regions"]):
        reg = schema["address_regions"][name]
        lines.append(f"| `{name}` | `{reg['base']}` | `{reg['size']}` | {reg['description']} |")
    lines.append("")

    # Each module
    for mod_name in sorted(schema["modules"]):
        mod = schema["modules"][mod_name]
        lines.append(f"## {mod_name}")
        lines.append(f"> **Base:** `{mod['base']}` | {mod.get('description', '')}")
        if "notes" in mod:
            for note in mod["notes"].values():
                lines.append(f"> ⚠️ {note}")
        lines.append("")
        lines.append("| Offset | Register | Access | Reset | Description |")
        lines.append("|--------|----------|--------|-------|-------------|")
        for reg_name in sorted(mod["registers"]):
            reg = mod["registers"][reg_name]
            arr = f"[{reg['array_size']}]" if reg.get("array_size") else ""
            lines.append(f"| `{reg['offset']}` | `{reg_name}{arr}` | {reg['access']} | `{reg['reset']}` | {reg.get('description', '')} |")
        lines.append("")

    # Opcodes
    lines.append("## Engine Opcodes (Firmware Dispatch)")
    lines.append("")
    lines.append("| Name | Value | Engine | Description |")
    lines.append("|------|-------|--------|-------------|")
    opcode_values = schema["opcodes"]["values"]
    for name in sorted(opcode_values, key=lambda n: opcode_values[n]["value"]):
        oc = opcode_values[name]
        lines.append(f"| `{name}` | `{oc['value']:#04x}` | {oc['engine']} | {oc['description']} |")
    lines.append("")

    lines.append("## ISA Opcodes")
    lines.append("")
    lines.append("| Name | Value (5-bit) | Description |")
    lines.append("|------|---------------|-------------|")
    isa_values = schema["isa_opcodes"]["values"]
    for name in sorted(isa_values, key=lambda n: isa_values[n]["value"]):
        oc = isa_values[name]
        lines.append(f"| `{name}` | `{oc['value']:#04x}` | {oc['description']} |")
    lines.append("")

    # Status codes
    lines.append("## Status Codes")
    lines.append("")
    lines.append("| Name | Value | Description |")
    lines.append("|------|-------|-------------|")
    for name in sorted(schema["status_codes"]["values"],
                        key=lambda n: schema["status_codes"]["values"][n]["value"]):
        sc = schema["status_codes"]["values"][name]
        lines.append(f"| `{name}` | {sc['value']} | {sc['description']} |")
    lines.append("")

    # Descriptors
    for desc_name in sorted(schema["descriptors"]):
        if desc_name == "description":
            continue
        desc = schema["descriptors"][desc_name]
        lines.append(f"## {desc_name} Descriptor ({desc['packed_size']} bytes)")
        if "notes" in desc:
            for note in desc["notes"]:
                lines.append(f"> {note}")
        lines.append("")
        lines.append("| Index | Offset | Field | Type | Description |")
        lines.append("|-------|--------|-------|------|-------------|")
        for f in desc["fields"]:
            lines.append(f"| {f['index']} | {f['offset']} | `{f['name']}` | {f['type']} | {f['description']} |")
        lines.append("")

    # Compatibility rules
    lines.append("## Compatibility")
    lines.append("")
    lines.append(f"- **Major version bump** ({schema['abi']['major']}): {schema['abi']['compatibility']['major_break']}")
    lines.append(f"- **Minor version bump** ({schema['abi']['major']}.x): {schema['abi']['compatibility']['minor_add']}")
    lines.append("")

    # Known discrepancies
    if "known_discrepancies" in schema:
        lines.append("## Known Discrepancies")
        lines.append("")
        for item in schema["known_discrepancies"]["items"]:
            sev = item["severity"].upper()
            lines.append(f"### {item['id']} [{sev}]")
            lines.append(f"{item['description']}")
            lines.append("")
            lines.append(f"**Sources:** {', '.join(item['sources'])}")
            lines.append("")

    return "\n".join(lines)


