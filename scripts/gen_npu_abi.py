# C header generator
# ═════════════════════════════════════════════════════════════════════

def gen_c_header(schema: dict[str, Any]) -> str:
    """Generate C/C++ header with defines and static_assert support."""
    lines: list[str] = []
    lines.append(f"/* {GENERATED_MARKER} */")
    lines.append(f"/* ABI version: {schema['abi']['version_string']} */")
    lines.append("")
    lines.append(f"#ifndef NPU_ABI_H")
    lines.append(f"#define NPU_ABI_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif")
    lines.append("")

    # ABI version macros
    lines.append("/* ── ABI Version ─────────────────────────────────────────────── */")
    lines.append(f"#define NPU_ABI_MAJOR {schema['abi']['major']}")
    lines.append(f"#define NPU_ABI_MINOR {schema['abi']['minor']}")
    lines.append(f'#define NPU_ABI_VERSION_STRING "{schema["abi"]["version_string"]}"')
    lines.append("")

    # Address regions
    lines.append("/* ── Address Regions ────────────────────────────────────────── */")
    for name in sorted(schema["address_regions"]):
        reg = schema["address_regions"][name]
        base = int(reg["base"], 16)
        size = int(reg["size"], 16)
        lines.append(f"#define NPU_{name}_BASE 0x{base:08X}UL")
        lines.append(f"#define NPU_{name}_SIZE 0x{size:08X}UL")
    lines.append("")

    # Register offsets for each module
    for mod_name in sorted(schema["modules"]):
        mod = schema["modules"][mod_name]
        lines.append(f"/* ── {mod_name} Registers (base: NPU_{mod_name}_BASE) ──── */")
        for reg_name in sorted(mod["registers"]):
            reg = mod["registers"][reg_name]
            off = int(reg["offset"], 16)
            desc = reg.get("description", "").split("\n")[0]
            lines.append(f"#define NPU_{mod_name}_{reg_name}_OFFSET 0x{off:04X}UL  /* {desc} */")
        lines.append("")

    # Struct typedefs for each module
    for mod_name in sorted(schema["modules"]):
        mod = schema["modules"][mod_name]
        c_basename = mod_name.lower()
        lines.append(f"typedef struct {{")
        current_offset = 0
        for reg_name in sorted(mod["registers"], key=lambda n: int(mod["registers"][n]["offset"], 16)):
            reg = mod["registers"][reg_name]
            off = int(reg["offset"], 16)
            # Add padding if needed
            if off > current_offset:
                pad_bytes = off - current_offset
                lines.append(f"    uint8_t _pad_{current_offset:04x}[{pad_bytes}];")
            arr = ""
            if reg.get("array_size"):
                arr = f"[{reg['array_size']}]"
            lines.append(f"    volatile uint32_t {reg_name}{arr};  /* 0x{off:04X}: {reg.get('description', '')} */")
            current_offset = off + 4 * (reg.get("array_size", 1))
        lines.append(f"}} npu_{c_basename}_t;")
        lines.append("")

    # Engine opcodes
    lines.append("/* ── Engine Opcodes ─────────────────────────────────────────── */")
    opcode_values = schema["opcodes"]["values"]
    for name in sorted(opcode_values, key=lambda n: opcode_values[n]["value"]):
        oc = opcode_values[name]
        lines.append(f"#define NPU_ENGINE_OP_{name} {oc['value']}  /* {oc['engine']}: {oc['description']} */")
    lines.append("")

    # ISA opcodes
    lines.append("/* ── ISA Opcodes ────────────────────────────────────────────── */")
    isa_values = schema["isa_opcodes"]["values"]
    for name in sorted(isa_values, key=lambda n: isa_values[n]["value"]):
        oc = isa_values[name]
        lines.append(f"#define NPU_ISA_OP_{name} {oc['value']}  /* {oc['description']} */")
    lines.append("")

    # Status codes
    lines.append("/* ── Status Codes ───────────────────────────────────────────── */")
    for name in sorted(schema["status_codes"]["values"],
                        key=lambda n: schema["status_codes"]["values"][n]["value"]):
        sc = schema["status_codes"]["values"][name]
        lines.append(f"#define NPU_STATUS_{name} {sc['value']}  /* {sc['description']} */")
    lines.append("")

    # Capability bits
    lines.append("/* ── Capability Bits ────────────────────────────────────────── */")
    for name in sorted(schema["capability_bits"]["bits"],
                        key=lambda n: schema["capability_bits"]["bits"][n]["bit"]):
        cb = schema["capability_bits"]["bits"][name]
        lines.append(f"#define NPU_CAP_{name} (1U << {cb['bit']})  /* {cb['description']} */")
    lines.append("")

    # SFU opcodes
    lines.append("/* ── SFU Sub-Opcodes ────────────────────────────────────────── */")
    for name in sorted(schema["sfu_sub_opcodes"]["values"],
                        key=lambda n: schema["sfu_sub_opcodes"]["values"][n]["value"]):
        so = schema["sfu_sub_opcodes"]["values"][name]
        lines.append(f"#define SFU_OP_{name} {so['value']}  /* {so['description']} */")
    lines.append("")

    # Vector opcodes
    lines.append("/* ── Vector Sub-Opcodes ─────────────────────────────────────── */")
    for name in sorted(schema["vector_sub_opcodes"]["values"],
                        key=lambda n: schema["vector_sub_opcodes"]["values"][n]["value"]):
        vo = schema["vector_sub_opcodes"]["values"][name]
        lines.append(f"#define VEC_OP_{name} {vo['value']}  /* {vo['description']} */")
    lines.append("")

    # INTC bit mappings
    lines.append("/* ── Interrupt Source Bits ──────────────────────────────────── */")
    for name in sorted(schema["intc_mappings"]["sources"],
                        key=lambda n: schema["intc_mappings"]["sources"][n]["bit"]):
        src = schema["intc_mappings"]["sources"][name]
        lines.append(f"#define INTC_{name} (1U << {src['bit']})  /* {src['description']} */")
    lines.append("")

    # Ring configuration
    lines.append("/* ── Ring Buffer Configuration ──────────────────────────────── */")
    rc = schema["rings"]["configuration"]
    lines.append(f"#define NPU_RING_ENTRIES {rc['ring_entries']}")
    lines.append(f"#define NPU_CMD_ENTRY_SIZE {rc['cmd_entry_size']}")
    lines.append(f"#define NPU_COMPLETION_ENTRY_SIZE {rc['completion_entry_size']}")
    lines.append("")

    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    lines.append("#endif /* NPU_ABI_H */")
    lines.append("")

    return "\n".join(lines)


