#!/usr/bin/env python3
"""
NPU ABI Schema Generator

Reads spec/npu_abi.json and generates deterministic bindings for:
  - Python:   gen/npu_abi.py
  - C:        gen/npu_abi.h
  - Firmware: gen/npu_abi_firmware.h
  - SystemVerilog: gen/npu_abi_pkg.sv
  - Markdown: gen/npu_abi.md

Modes:
  python3 scripts/gen_npu_abi.py --generate       # write artifacts
  python3 scripts/gen_npu_abi.py --check           # validate artifacts match schema (exit 0/1)

Two consecutive --generate runs produce byte-identical output.
"""

import argparse
import filecmp
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Any


# ── Constants ───────────────────────────────────────────────────────
GENERATED_MARKER = (
    "DO NOT EDIT — generated by scripts/gen_npu_abi.py from spec/npu_abi.json"
)

REPO = Path(__file__).resolve().parent.parent
SCHEMA_PATH = REPO / "spec" / "npu_abi.json"


# ═════════════════════════════════════════════════════════════════════
# Schema loader
# ═════════════════════════════════════════════════════════════════════

def load_schema() -> dict[str, Any]:
    """Load and validate the ABI schema JSON."""
    if not SCHEMA_PATH.is_file():
        sys.exit(f"ERROR: Schema not found at {SCHEMA_PATH}")
    with open(SCHEMA_PATH, encoding="utf-8") as f:
        data = json.load(f)
    _validate_schema(data)
    return data


def _validate_schema(data: dict[str, Any]) -> None:
    """Basic structural validation of the schema."""
    required_top = ["abi", "address_regions", "modules", "opcodes",
                    "descriptors", "rings", "capability_bits"]
    for key in required_top:
        if key not in data:
            sys.exit(f"Schema validation error: missing top-level key '{key}'")

    # Validate registers don't overlap within a module
    for mod_name, mod in data["modules"].items():
        seen: dict[int, str] = {}
        for reg_name, reg in sorted(mod.get("registers", {}).items(),
                                     key=lambda x: int(x[1]["offset"], 16)):
            off = int(reg["offset"], 16)
            if off in seen:
                sys.exit(
                    f"Schema error: {mod_name}.{reg_name} offset 0x{off:02X} "
                    f"collides with {mod_name}.{seen[off]}"
                )
            seen[off] = reg_name


# ═════════════════════════════════════════════════════════════════════
# Python generator
# ═════════════════════════════════════════════════════════════════════

def gen_python(schema: dict[str, Any]) -> str:
    """Generate Python constants module."""
    lines: list[str] = []
    lines.append(f"# {GENERATED_MARKER}")
    lines.append(f"# ABI version: {schema['abi']['version_string']}")
    lines.append("")
    lines.append('"""')
    lines.append(f"  CaduceusCore NPU ABI v{schema['abi']['version_string']}")
    lines.append(f"  Generated from: spec/npu_abi.json")
    lines.append('"""')
    lines.append("")
    lines.append("from enum import IntEnum")
    lines.append("")

    # Address regions
    lines.append("# ═══ Address Regions ═══")
    lines.append("")
    lines.append("class Addr:")
    lines.append('    """Base addresses (byte-addressable, 32-bit aligned)."""')
    for name in sorted(schema["address_regions"]):
        reg = schema["address_regions"][name]
        base = int(reg["base"], 16)
        lines.append(f"    {name:22s} = 0x{base:08X}")
    lines.append("")
    lines.append("")

    # Modules
    for mod_name in sorted(schema["modules"]):
        mod = schema["modules"][mod_name]
        lines.append(f"# ═══ {mod_name} ({mod['base']}) ═══")
        lines.append(f"# {mod.get('description', '')}")
        lines.append("")
        lines.append(f"class {mod_name}:")
        lines.append(f"    BASE = Addr.{mod_name}")
        lines.append("")
        for reg_name in sorted(mod["registers"]):
            reg = mod["registers"][reg_name]
            off = int(reg["offset"], 16)
            desc = reg.get("description", "")
            access = reg.get("access", "").upper()
            fields_str = ""
            if "fields" in reg:
                fields_strs = []
                for fname, finfo in sorted(reg["fields"].items()):
                    bits = finfo["bits"]
                    if bits[0] == bits[1]:
                        fields_strs.append(f"bit[{bits[0]}]={fname}")
                    else:
                        fields_strs.append(f"[{bits[0]}:{bits[1]}]={fname}")
                fields_str = " (" + ", ".join(fields_strs) + ")"
            arr = ""
            if reg.get("array_size"):
                arr = f" [{reg['array_size']}]"
            lines.append(f"    {reg_name:22s} = 0x{off:04X}  # {access}: {desc}{fields_str}{arr}")
        lines.append("")
        lines.append("")

    # Opcodes (engine-level)
    lines.append("# ═══ Engine Opcodes (firmware dispatch) ═══")
    lines.append("")
    lines.append("class EngineOp(IntEnum):")
    lines.append('    """Engine-level opcode shared between host (Python) and firmware (C)."""')
    opcode_values = schema["opcodes"]["values"]
    for name in sorted(opcode_values, key=lambda n: opcode_values[n]["value"]):
        oc = opcode_values[name]
        lines.append(f"    {name:22s} = {oc['value']:#04x}  # {oc['engine']}: {oc['description']}")
    lines.append("")
    lines.append("")

    # ISA opcodes
    lines.append("# ═══ ISA Opcodes (instruction set) ═══")
    lines.append("")
    lines.append("class OpCode(IntEnum):")
    lines.append('    """NPU instruction opcodes (5-bit)."""')
    isa_values = schema["isa_opcodes"]["values"]
    for name in sorted(isa_values, key=lambda n: isa_values[n]["value"]):
        oc = isa_values[name]
        lines.append(f"    {name:22s} = {oc['value']:#04x}  # {oc['description']}")
    lines.append("")
    lines.append("")

    # Status codes
    lines.append("# ═══ Status Codes ═══")
    lines.append("")
    lines.append("class StatusCode(IntEnum):")
    for name in sorted(schema["status_codes"]["values"],
                        key=lambda n: schema["status_codes"]["values"][n]["value"]):
        sc = schema["status_codes"]["values"][name]
        lines.append(f"    {name:22s} = {sc['value']}  # {sc['description']}")
    lines.append("")
    lines.append("")

    # Capability bits
    lines.append("# ═══ Capability Bits ═══")
    lines.append("")
    for name in sorted(schema["capability_bits"]["bits"],
                        key=lambda n: schema["capability_bits"]["bits"][n]["bit"]):
        cb = schema["capability_bits"]["bits"][name]
        lines.append(f"CAP_{name} = 1 << {cb['bit']:2d}  # {cb['description']}")
    lines.append("")
    lines.append("")

    # SFU sub-opcodes
    lines.append("# ═══ SFU Sub-Opcodes ═══")
    lines.append("")
    lines.append("class SFUOp(IntEnum):")
    for name in sorted(schema["sfu_sub_opcodes"]["values"],
                        key=lambda n: schema["sfu_sub_opcodes"]["values"][n]["value"]):
        so = schema["sfu_sub_opcodes"]["values"][name]
        lines.append(f"    {name:22s} = {so['value']}  # {so['description']}")
    lines.append("")
    lines.append("")

    # Vector sub-opcodes
    lines.append("# ═══ Vector Sub-Opcodes ═══")
    lines.append("")
    lines.append("class VectorOp(IntEnum):")
    for name in sorted(schema["vector_sub_opcodes"]["values"],
                        key=lambda n: schema["vector_sub_opcodes"]["values"][n]["value"]):
        vo = schema["vector_sub_opcodes"]["values"][name]
        lines.append(f"    {name:22s} = {vo['value']}  # {vo['description']}")
    lines.append("")
    lines.append("")

    # MXU dtype
    lines.append("# ═══ MXU Data Types ═══")
    lines.append("")
    lines.append("class MXUDType(IntEnum):")
    for name in sorted(schema["mxu_dtype"]["values"],
                        key=lambda n: schema["mxu_dtype"]["values"][n]["value"]):
        dt = schema["mxu_dtype"]["values"][name]
        lines.append(f"    {name:22s} = {dt['value']}  # {dt['description']}")
    lines.append("")
    lines.append("")

    # INTC mappings
    lines.append("# ═══ Interrupt Source Bits ═══")
    lines.append("")
    for name in sorted(schema["intc_mappings"]["sources"],
                        key=lambda n: schema["intc_mappings"]["sources"][n]["bit"]):
        src = schema["intc_mappings"]["sources"][name]
        lines.append(f"INTC_{name:8s} = 1 << {src['bit']}  # {src['description']}")
    lines.append("")

    # Descriptor sizes
    lines.append("# ═══ Descriptor Sizes ═══")
    lines.append("")
    for desc_name in sorted(schema["descriptors"]):
        if desc_name == "description":
            continue
        desc = schema["descriptors"][desc_name]
        lines.append(f"DESC_{desc_name}_SIZE = {desc['packed_size']}  # {desc.get('notes', [''])[0] if desc.get('notes') else ''}")
    lines.append("")

    # Ring configuration
    lines.append("# ═══ Ring Buffer Configuration ═══")
    lines.append("")
    rc = schema["rings"]["configuration"]
    lines.append(f"RING_ENTRIES          = {rc['ring_entries']}")
    lines.append(f"CMD_ENTRY_SIZE        = {rc['cmd_entry_size']}")
    lines.append(f"COMPLETION_ENTRY_SIZE = {rc['completion_entry_size']}")
    lines.append("")

    return "\n".join(lines)


