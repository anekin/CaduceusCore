# SystemVerilog package generator
# ═════════════════════════════════════════════════════════════════════

def gen_sv_package(schema: dict[str, Any]) -> str:
    """Generate SystemVerilog package with localparam declarations."""
    lines: list[str] = []
    lines.append(f"// {GENERATED_MARKER}")
    lines.append(f"// ABI version: {schema['abi']['version_string']}")
    lines.append("")
    lines.append("package npu_abi_pkg;")
    lines.append("")
    lines.append(f"  // ABI version")
    lines.append(f"  localparam int unsigned NPU_ABI_MAJOR = {schema['abi']['major']};")
    lines.append(f"  localparam int unsigned NPU_ABI_MINOR = {schema['abi']['minor']};")
    lines.append("")

    # Address regions
    lines.append("  // ── Address Regions ───────────────────────────────────────")
    for name in sorted(schema["address_regions"]):
        reg = schema["address_regions"][name]
        base = int(reg["base"], 16)
        size = int(reg["size"], 16)
        lines.append(f"  localparam logic [31:0] NPU_{name}_BASE = 32'h{base:08X};")
        lines.append(f"  localparam logic [31:0] NPU_{name}_SIZE = 32'h{size:08X};")
    lines.append("")

    # Register offsets for each module
    for mod_name in sorted(schema["modules"]):
        mod = schema["modules"][mod_name]
        lines.append(f"  // ── {mod_name} Registers (NPU_{mod_name}_BASE) ─────────")
        for reg_name in sorted(mod["registers"]):
            reg = mod["registers"][reg_name]
            off = int(reg["offset"], 16)
            lines.append(f"  localparam logic [11:0] NPU_{mod_name}_{reg_name}_OFFSET = 12'h{off:03X};")
        lines.append("")

    # Opcodes
    lines.append("  // ── Engine Opcodes ────────────────────────────────────────")
    opcode_values = schema["opcodes"]["values"]
    for name in sorted(opcode_values, key=lambda n: opcode_values[n]["value"]):
        oc = opcode_values[name]
        lines.append(f"  localparam logic [7:0] NPU_ENGINE_OP_{name} = 8'h{oc['value']:02X};")
    lines.append("")

    # ISA opcodes
    lines.append("  // ── ISA Opcodes ───────────────────────────────────────────")
    isa_values = schema["isa_opcodes"]["values"]
    for name in sorted(isa_values, key=lambda n: isa_values[n]["value"]):
        oc = isa_values[name]
        lines.append(f"  localparam logic [4:0] NPU_ISA_OP_{name} = 5'h{oc['value']:02X};")
    lines.append("")

    # Status codes
    lines.append("  // ── Status Codes ──────────────────────────────────────────")
    for name in sorted(schema["status_codes"]["values"],
                        key=lambda n: schema["status_codes"]["values"][n]["value"]):
        sc = schema["status_codes"]["values"][name]
        lines.append(f"  localparam logic [31:0] NPU_STATUS_{name} = 32'h{sc['value']:08X};")
    lines.append("")

    # Capability bits
    lines.append("  // ── Capability Bits ───────────────────────────────────────")
    for name in sorted(schema["capability_bits"]["bits"],
                        key=lambda n: schema["capability_bits"]["bits"][n]["bit"]):
        cb = schema["capability_bits"]["bits"][name]
        lines.append(f"  localparam logic [31:0] NPU_CAP_{name} = 32'h{1 << cb['bit']:08X};")
    lines.append("")

    # INTC
    lines.append("  // ── Interrupt Source Bits ─────────────────────────────────")
    for name in sorted(schema["intc_mappings"]["sources"],
                        key=lambda n: schema["intc_mappings"]["sources"][n]["bit"]):
        src = schema["intc_mappings"]["sources"][name]
        lines.append(f"  localparam logic [6:0] NPU_INTC_{name}_BIT = 7'h{1 << src['bit']:02X};")
    lines.append("")

    # Ring configuration
    lines.append("  // ── Ring Buffer Configuration ─────────────────────────────")
    rc = schema["rings"]["configuration"]
    lines.append(f"  localparam int unsigned NPU_RING_ENTRIES = {rc['ring_entries']};")
    lines.append(f"  localparam int unsigned NPU_CMD_ENTRY_SIZE = {rc['cmd_entry_size']};")
    lines.append(f"  localparam int unsigned NPU_COMPLETION_ENTRY_SIZE = {rc['completion_entry_size']};")
    lines.append("")

    lines.append("endpackage : npu_abi_pkg")
    lines.append("")

    return "\n".join(lines)


